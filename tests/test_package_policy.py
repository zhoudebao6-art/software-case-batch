import base64
from pathlib import Path
import sys
import unittest
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from package_policy import excluded_delivery_document, audit_delivery_text


class PackagePolicyTests(unittest.TestCase):
    def test_guides_and_process_artifacts_excluded_at_any_depth(self):
        for name in ('运行说明.txt', 'docs/使用说明.md', 'docs/用户手册.html', '开发说明.rst',
                     '设计制作说明.docx', 'nested/原件解析.json', 'README.md', 'x/rEaD-Me.zh.txt',
                     'x/read_me/guide.txt', 'docs/user-guide.md', 'run_instructions.txt',
                     'source-analysis.json', 'docs/ai-generation-notes.md', 'prompts.yaml'):
            with self.subTest(name=name):
                self.assertIsNotNone(excluded_delivery_document(name))

    def test_runtime_sources_and_required_license_are_retained(self):
        for name in ('requirements.txt', 'LICENSES/DATA-NOTICE.txt', 'LICENSE', 'NOTICE.md',
                     'app/import_parser.py', 'app/source_parser.py', 'web/app.js',
                     '启动.ps1', 'app/runtime.json', 'config/example.yaml'):
            with self.subTest(name=name):
                self.assertIsNone(excluded_delivery_document(name))

    def test_data_nature_and_production_narratives_detected(self):
        for text in ('Synthetic data for evaluation.', 'simulated_data = []', 'mockData = []',
                     'Data are calculation outputs for local software evaluation.',
                     'They are not measurements from a production line.', 'AI generated dataset.',
                     'Generated by ChatGPT.', 'Original document parsing notes.', '数据性质：计算构造数据'):
            with self.subTest(text=text):
                self.assertTrue(audit_delivery_text('app/server.py', text))

    def test_encoded_and_concatenated_text_is_audited(self):
        for text in (r'label="\u6a21\u62df"', 'label="&#27169;&#25311;"',
                     'label="%E6%A8%A1%E6%8B%9F"', 'label="模" + "拟"',
                     'label="syn" + "thetic data"', 'label="模\u200b拟"',
                     r'label="\6a21 \62df"', 'label=String.fromCharCode(0x6a21,0x62df)',
                     'payload="' + base64.b64encode('mock data'.encode()).decode() + '"'):
            with self.subTest(text=text):
                self.assertTrue(audit_delivery_text('web/app.js', text))

    def test_business_algorithms_and_minimal_attribution_are_clean(self):
        text = '''from unittest.mock import patch
def operating_point(voltage, load, elapsed, disturbance=0.0):
    current = (voltage - constant * omega) / resistance
    return current, rpm
Sampling interval: 0.1 seconds.
Initialize database from CSV; keep version tokens.
Robot Execution Failures
Authors: Luis S. Lopes and Luis M. Camarinha-Matos
License: Creative Commons Attribution 4.0 International
Changes: Material has been modified.
No endorsement by the dataset authors is implied.'''
        self.assertEqual(audit_delivery_text('LICENSES/DATA-NOTICE.txt', text), [])

    def test_actual_location_is_returned(self):
        hits = audit_delivery_text('app/a.py', '# normal\n# mock data\n# normal')
        self.assertEqual(hits[0]['path'], 'app/a.py')
        self.assertEqual(hits[0]['line'], 2)


if __name__ == '__main__':
    unittest.main()
